import assert from "node:assert/strict";
import { once } from "node:events";
import { createServer } from "node:http";
import { readFile } from "node:fs/promises";
import { test } from "node:test";
import { chromium } from "playwright";

test("console reservations are explicit, session-bound, expiry-aware and never restored after logout", async () => {
  const html = await readFile(new URL("../src/agent-console.html", import.meta.url));
  const script = await readFile(new URL("../src/agent-console.js", import.meta.url));
  const server = createServer((request, response) => {
    response.setHeader("Content-Type", request.url === "/agent/console.js" ? "text/javascript" : "text/html");
    response.end(request.url === "/agent/console.js" ? script : html);
  });
  server.listen(0, "127.0.0.1");
  await once(server, "listening");
  const address = server.address();
  assert.ok(address && typeof address !== "string");
  const origin = `http://127.0.0.1:${address.port}`;
  const browser = await chromium.launch();
  const page = await browser.newPage();
  const requestId = "aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa";
  const leaseId = "bbbbbbbb-bbbb-bbbb-bbbb-bbbbbbbbbbbb";
  const errors: string[] = [];
  const calls: { path: string; body: { deviceId: string; leaseId?: string } }[] = [];
  let mode = "valid";
  let finishHeld: (() => void) | undefined;
  let profileAllowed = true;
  let releaseHeld: (() => void) | undefined;
  try {
    page.on("pageerror", (error) => errors.push(error.message));
    await page.clock.install();
    await page.route("**/auth/session", (route) => route.fulfill({
      contentType: "application/json", body: JSON.stringify({
        customer: "customer-a", csrf: "a".repeat(43), expiresAt: new Date(Date.now() + 300000).toISOString(),
      }),
    }));
    await page.route("**/agent/profile", (route) => route.fulfill({
      status: profileAllowed ? 200 : 403, contentType: "application/json",
      body: JSON.stringify({ customer: "customer-a", agent: { extension: "1001", displayName: "Alice" } }),
    }));
    await page.route("**/agent/device-lease**", async (route) => {
      const request = route.request();
      assert.equal(request.method(), "POST");
      assert.equal(request.headers()["x-csrf-token"], "a".repeat(43));
      assert.equal(request.headers().authorization, undefined);
      const body = request.postDataJSON();
      assert.match(body.deviceId, /^[0-9a-f-]{36}$/);
      const path = new URL(request.url()).pathname;
      assert.deepEqual(Object.keys(body).sort(), path.endsWith("device-lease") ? ["deviceId"] : ["deviceId", "leaseId"]);
      calls.push({ path, body });
      const snapshot = mode;
      if (snapshot === "held") {
        await new Promise<void>((resolve) => { releaseHeld = resolve; });
        // Simulate an abort racing a response already generated by the server.
        await route.fulfill({ contentType: "application/json", headers: { "X-Request-Id": requestId },
          body: JSON.stringify({ customer: "customer-a", lease: { id: leaseId, expiresAt: Date.now() + 50000 } }) });
        finishHeld?.();
        return;
      }
      if (snapshot === "network") { await route.abort("failed"); return; }
      await route.fulfill({ status: snapshot === "conflict" ? 409 : snapshot === "failed" ? 503 :
        snapshot === "unauthenticated" ? 401 : 200,
      contentType: "application/json", headers: { "X-Request-Id": requestId },
      body: JSON.stringify({ customer: snapshot === "mismatch" ? "customer-b" : "customer-a",
        ...(path.endsWith("/release") ? { code: snapshot === "bad-release" ? "wrong" : "agent_device_released" } :
          { lease: { id: snapshot === "bad-id" ? "bad" : leaseId,
            expiresAt: snapshot === "bad-expiry" ? Date.now() + 400000 : Date.now() + 50000 } }) }) });
    });
    await page.route("**/auth/logout", (route) => route.fulfill({ status: 200, body: "{}" }));
    await page.goto(origin + "/agent/customer-a");
    await page.locator("#assignment-status").filter({ hasText: "Assignment loaded" }).waitFor();
    assert.equal(calls.length, 0, "Landing must not auto-acquire");
    const reserve = page.getByRole("button", { name: "Reserve this device", exact: true });
    const renew = page.getByRole("button", { name: "Renew reservation", exact: true });
    const release = page.getByRole("button", { name: "Release reservation", exact: true });
    await reserve.click();
    await page.locator("#device-status").filter({ hasText: "Device reserved until" }).waitFor();
    const firstDevice = calls[0].body.deviceId;
    assert.equal(await reserve.isVisible(), false);
    await renew.click();
    await page.locator("#device-status").filter({ hasText: "Device reserved until" }).waitFor();
    assert.equal(calls[1].body.deviceId, firstDevice);
    assert.equal(calls[1].body.leaseId, leaseId);
    mode = "failed";
    await release.click();
    await page.getByRole("alert").filter({ hasText: "Reservation change not confirmed" }).waitFor();
    assert.equal(await release.isVisible(), true, "Uncertain release retains retry handle");
    assert.ok((await page.locator("#device-status").textContent())?.includes(requestId));
    mode = "bad-release";
    await release.click();
    await page.getByRole("alert").filter({ hasText: "Invalid release response" }).waitFor();
    mode = "valid";
    await release.click();
    await page.locator("#device-status").filter({ hasText: "Reservation released" }).waitFor();
    for (mode of ["conflict", "failed", "mismatch", "bad-id", "bad-expiry", "network"]) {
      await reserve.click();
      await page.getByRole("alert").filter({ hasText: "Reservation change not confirmed" }).waitFor();
      assert.equal(await reserve.isVisible(), true);
    }
    assert.ok(calls.every((call) => call.body.deviceId === firstDevice), "Uncertain acquisition retries retain device identity");
    mode = "valid";
    await reserve.click();
    await page.locator("#device-status").filter({ hasText: "Device reserved until" }).waitFor();
    const before = calls.length;
    await page.clock.fastForward(50001);
    await page.locator("#device-status").filter({ hasText: "Reservation expired locally" }).waitFor();
    assert.equal(calls.length, before, "Expiry must not auto-renew or release");
    assert.equal(await renew.isVisible(), false);
    await page.clock.setSystemTime(new Date());
    mode = "held";
    const pending = page.waitForRequest("**/agent/device-lease");
    await reserve.click();
    await pending;
    assert.equal(await reserve.isDisabled(), true);
    assert.equal(await page.getByRole("button", { name: "Sign out", exact: true }).isEnabled(), true);
    await page.getByRole("button", { name: "Sign out", exact: true }).click();
    await page.getByText("Sign in to view your agent assignment.", { exact: true }).waitFor();
    const finished = new Promise<void>((resolve) => { finishHeld = resolve; });
    assert.ok(releaseHeld); releaseHeld();
    await finished;
    assert.equal(await page.locator("#device-reservation").isHidden(), true);
    assert.equal(await page.locator("#assignment dd").count(), 0);
    mode = "valid";
    await page.reload();
    await page.locator("#assignment-status").filter({ hasText: "Assignment loaded" }).waitFor();
    await reserve.click();
    await page.locator("#device-status").filter({ hasText: "Device reserved until" }).waitFor();
    assert.notEqual(calls.at(-1)?.body.deviceId, firstDevice, "Reload does not persist device/session data");
    mode = "unauthenticated";
    await renew.click();
    await page.getByText("Application session is no longer valid. Sign in again.", { exact: true }).waitFor();
    assert.equal(await page.locator("#device-reservation").isHidden(), true);
    profileAllowed = false;
    await page.reload();
    await page.getByRole("alert").filter({ hasText: "Agent access is not permitted." }).waitFor();
    assert.equal(await page.locator("#device-reservation").isHidden(), true);
    assert.deepEqual(errors, []);
  } finally {
    await page.close(); await browser.close();
    server.closeAllConnections();
    await new Promise<void>((resolve, reject) => server.close((error) => error ? reject(error) : resolve()));
  }
});

test("agent console renders literal profiles, clears stale data, guards session lifecycle and confirms logout", async () => {
  const html = await readFile(new URL("../src/agent-console.html", import.meta.url));
  const script = await readFile(new URL("../src/agent-console.js", import.meta.url));
  const server = createServer((request, response) => {
    response.setHeader("Content-Type", request.url === "/agent/console.js" ? "text/javascript" : "text/html");
    response.end(request.url === "/agent/console.js" ? script : html);
  });
  server.listen(0, "127.0.0.1");
  await once(server, "listening");
  const address = server.address();
  assert.ok(address && typeof address !== "string");
  const origin = `http://127.0.0.1:${address.port}`;
  const browser = await chromium.launch();
  const context = await browser.newContext();
  let mode = "valid";
  let sessionMode = "valid";
  let failLogout = true;
  let profileReads = 0;
  let releaseProfile: (() => void) | undefined;
  const requestId = "aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa";
  const errors: string[] = [];
  try {
    const page = await context.newPage();
    page.on("pageerror", (error) => errors.push(error.message));
    await page.route("**/auth/session", async (route) => route.fulfill({ status: sessionMode === "unauthenticated" ? 401 : 200,
      contentType: "application/json", headers: { "X-Request-Id": requestId },
      body: JSON.stringify({ customer: sessionMode === "mismatch" ? "customer-b" : "customer-a",
        csrf: "a".repeat(43), expiresAt: new Date(Date.now() + 300000).toISOString() }) }));
    await page.route("**/api/customers/customer-a/agent/profile", async (route) => {
      profileReads++;
      if (mode === "held-logout") await new Promise<void>((resolve) => { releaseProfile = resolve; });
      if (mode === "held") await new Promise((resolve) => setTimeout(resolve, 500));
      await route.fulfill({ status: mode === "failed" ? 503 : mode === "unauthorized" ? 401 : 200,
        contentType: "application/json", headers: { "X-Request-Id": requestId },
        body: JSON.stringify({ customer: mode === "mismatch" ? "customer-b" : "customer-a",
          agent: { extension: "1001", displayName: "<img src=x onerror=alert(1)>" } }) });
    });
    await page.route("**/auth/logout", async (route) => {
      assert.equal(route.request().method(), "POST");
      assert.equal(route.request().headers()["x-csrf-token"], "a".repeat(43));
      await route.fulfill({ status: failLogout ? 503 : 204, headers: { "X-Request-Id": requestId }, body: "" });
    });
    await page.goto(origin + "/agent/customer-a");
    await page.locator("#assignment-status").filter({ hasText: "Assignment loaded" }).waitFor();
    assert.ok((await page.locator("#assignment").textContent())?.includes("<img src=x onerror=alert(1)>"));
    assert.equal(await page.locator("img").count(), 0);
    mode = "held";
    await page.getByRole("button", { name: "Refresh assignment" }).click();
    assert.equal(await page.locator("#assignment").isHidden(), true);
    assert.equal(await page.getByRole("button", { name: "Refresh assignment" }).isDisabled(), true);
    await page.locator("#assignment-status").filter({ hasText: "Assignment loaded" }).waitFor();
    mode = "failed";
    await page.getByRole("button", { name: "Refresh assignment" }).click();
    await page.getByRole("alert").filter({ hasText: requestId }).waitFor();
    assert.equal(await page.locator("#assignment dd").count(), 0);
    const reads = profileReads;
    await page.waitForTimeout(100);
    assert.equal(profileReads, reads, "Failures must not cause automatic retries");
    mode = "mismatch";
    await page.getByRole("button", { name: "Refresh assignment" }).click();
    await page.getByRole("alert").filter({ hasText: "Invalid agent assignment response" }).waitFor();
    mode = "valid";
    await page.getByRole("button", { name: "Refresh assignment" }).click();
    await page.locator("#assignment-status").filter({ hasText: "Assignment loaded" }).waitFor();
    await page.getByRole("button", { name: "Sign out", exact: true }).click();
    await page.getByRole("alert").filter({ hasText: "Sign out was not confirmed" }).waitFor();
    assert.equal(await page.getByRole("button", { name: "Sign out", exact: true }).isEnabled(), true);
    failLogout = false;
    await page.getByRole("button", { name: "Sign out", exact: true }).click();
    await page.getByText("Sign in to view your agent assignment.", { exact: true }).waitFor();
    assert.equal(await page.locator("#assignment dd").count(), 0);
    assert.ok((await page.getByRole("link", { name: "Sign in" }).getAttribute("href"))?.includes("workspace=agent"));
    sessionMode = "mismatch";
    const before = profileReads;
    await page.reload();
    await page.getByRole("alert").filter({ hasText: "mismatched application session" }).waitFor();
    assert.equal(profileReads, before);
    sessionMode = "valid";
    await page.clock.install();
    await page.reload();
    await page.locator("#assignment-status").filter({ hasText: "Assignment loaded" }).waitFor();
    await page.clock.fastForward(300001);
    await page.getByText("Session expired. Sign in again.", { exact: true }).waitFor();
    assert.equal(await page.locator("#assignment dd").count(), 0);
    await page.clock.resume();
    await page.clock.setSystemTime(new Date());
    mode = "unauthorized";
    await page.reload();
    await page.getByText("Application session is no longer valid. Sign in again.", { exact: true }).waitFor();
    assert.equal(await page.locator("#assignment dd").count(), 0);
    mode = "valid";
    await page.reload();
    await page.locator("#assignment-status").filter({ hasText: "Assignment loaded" }).waitFor();
    mode = "held-logout";
    const pending = page.waitForRequest("**/api/customers/customer-a/agent/profile");
    await page.getByRole("button", { name: "Refresh assignment" }).click();
    await pending;
    assert.equal(await page.getByRole("button", { name: "Sign out", exact: true }).isEnabled(), true);
    await page.getByRole("button", { name: "Sign out", exact: true }).click();
    await page.getByText("Sign in to view your agent assignment.", { exact: true }).waitFor();
    assert.ok(releaseProfile);
    releaseProfile();
    await page.waitForTimeout(200);
    assert.equal(await page.locator("#assignment dd").count(), 0, "Late profile response must not repopulate a signed-out console");
    assert.equal(await page.getByRole("button", { name: "Refresh assignment" }).isVisible(), false);
    assert.deepEqual(errors, []);
  } finally {
    await context.close(); await browser.close();
    server.closeAllConnections();
    await new Promise<void>((resolve, reject) => server.close((error) => error ? reject(error) : resolve()));
  }
});
